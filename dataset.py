"""Dataset + pre-processing for crowd counting (ShanghaiTech-style layout).

Expected folder layout (ShanghaiTech Part A / B):
    data_root/
        train_data/images/IMG_1.jpg
        train_data/ground_truth/GT_IMG_1.mat      # contains image_info[0,0].location -> (N,2) head points (x, y)
        test_data/images/...
        test_data/ground_truth/...

Ground-truth density maps are generated by placing a Gaussian at every head
annotation, so the sum of the map equals the person count.
"""
import os
import random

import cv2
import numpy as np
import scipy.io as sio
import torch
from scipy.ndimage import gaussian_filter
from torch.utils.data import Dataset

MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)
DOWNSAMPLE = 8  # the model outputs a density map at 1/8 input resolution


def load_points(mat_path):
    mat = sio.loadmat(mat_path)
    pts = mat["image_info"][0, 0][0, 0][0]  # (N, 2) -> x, y
    return np.asarray(pts, dtype=np.float32)


def make_density_map(shape_hw, points, sigma=4.0):
    """Create a density map whose sum equals len(points)."""
    h, w = shape_hw
    dm = np.zeros((h, w), dtype=np.float32)
    for x, y in points:
        xi, yi = min(w - 1, max(0, int(round(x)))), min(h - 1, max(0, int(round(y))))
        dm[yi, xi] += 1.0
    return gaussian_filter(dm, sigma=sigma, mode="constant")


def downsample_density(dm, factor=DOWNSAMPLE):
    """Sum-pool the density map so the total count is preserved."""
    h, w = dm.shape
    h2, w2 = h // factor, w // factor
    dm = dm[: h2 * factor, : w2 * factor]
    return dm.reshape(h2, factor, w2, factor).sum(axis=(1, 3))


class CrowdDataset(Dataset):
    def __init__(self, split_dir, train=True, crop_size=256, sigma=4.0):
        self.img_dir = os.path.join(split_dir, "images")
        self.gt_dir = os.path.join(split_dir, "ground_truth")
        self.files = sorted(f for f in os.listdir(self.img_dir) if f.lower().endswith((".jpg", ".png")))
        self.train, self.crop, self.sigma = train, crop_size, sigma

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        name = self.files[idx]
        img = cv2.cvtColor(cv2.imread(os.path.join(self.img_dir, name)), cv2.COLOR_BGR2RGB)
        pts = load_points(os.path.join(self.gt_dir, "GT_" + os.path.splitext(name)[0] + ".mat"))
        h, w = img.shape[:2]

        # make sure the image is at least crop-sized and divisible by 8
        if self.train and (h < self.crop or w < self.crop):
            s = max(self.crop / h, self.crop / w)
            img = cv2.resize(img, (int(w * s) + 1, int(h * s) + 1))
            pts = pts * s
            h, w = img.shape[:2]

        dm = make_density_map((h, w), pts, self.sigma)

        if self.train:
            y0 = random.randint(0, h - self.crop)
            x0 = random.randint(0, w - self.crop)
            img = img[y0:y0 + self.crop, x0:x0 + self.crop]
            dm = dm[y0:y0 + self.crop, x0:x0 + self.crop]
            if random.random() < 0.5:  # horizontal flip augmentation
                img, dm = img[:, ::-1], dm[:, ::-1]
            # brightness jitter
            img = np.clip(img.astype(np.float32) * random.uniform(0.8, 1.2), 0, 255)
        else:
            h8, w8 = h // DOWNSAMPLE * DOWNSAMPLE, w // DOWNSAMPLE * DOWNSAMPLE
            img, dm = img[:h8, :w8], dm[:h8, :w8]

        dm_small = downsample_density(np.ascontiguousarray(dm))
        img = preprocess(np.ascontiguousarray(img))
        return torch.from_numpy(img), torch.from_numpy(dm_small).unsqueeze(0), float(len(pts))


def preprocess(img_rgb):
    """uint8/float RGB (H,W,3) -> normalised float32 (3,H,W)."""
    x = img_rgb.astype(np.float32) / 255.0
    x = (x - MEAN) / STD
    return x.transpose(2, 0, 1)
